/** 낱말 묶음 하나: 법무 검토 표(ai/AIT/eval/법무검토_새표현.md)가 이 모양에서 만들어진다. 묶음 이름 · 위험은 사람이 읽는 말 */
export interface TermFamily { id: string; label: string; risk: '낮음' | '중간' | '높음'; note: string; terms: readonly string[] }
export interface PatternFamily {
  id: string; label: string; risk: '낮음' | '중간' | '높음'; note: string; re: RegExp;
  /** 걸린 자리 바로 앞 글이 이 모양으로 끝나면 건너뛴다. 뒤돌아보기((?<!…))를 쓰지 않으려는 것 — 오래된 브라우저(Safari 16.3 이하)에서 정규식 문법 오류가 나면 앱 전체가 멈추기 때문 */
  unless?: RegExp;
}

/** 정규식 묶음 하나가 key 에 걸리는가(unless 가 있으면 앞 글을 보고 건너뛴다) */
export function matchesFamily(key: string, f: PatternFamily): boolean {
  if (!f.unless) return f.re.test(key);
  const g = new RegExp(f.re.source, f.re.flags.includes('g') ? f.re.flags : f.re.flags + 'g');
  let m: RegExpExecArray | null;
  while ((m = g.exec(key)) !== null) {
    if (m[0].length === 0) { g.lastIndex += 1; continue; }
    if (!f.unless.test(key.slice(Math.max(0, m.index - 40), m.index))) return true;
  }
  return false;
}

