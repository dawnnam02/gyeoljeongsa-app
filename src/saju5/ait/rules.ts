/** 규칙표로 한 문장(또는 글 한 칸)을 검사한다. input이 주어지면 inputExempt 규칙은 입력에 이미 있던 낱말을 봐준다. */
export function checkText(text: string, rules: readonly Rule[], opts: { input?: string; allowPhrases?: readonly string[] } = {}): Hit[] {
  let t = String(text ?? '');
  for (const p of opts.allowPhrases ?? []) t = t.split(p).join('');
  const hits: Hit[] = [];
  const nInput = opts.input ? normalizeForQuote(opts.input) : '';
  for (const rule of rules) {
    const m = rule.re.exec(t);
    if (!m) continue;
    const word = m[0];
    if (rule.inputExempt && nInput && nInput.includes(normalizeForQuote(word)) && normalizeForQuote(word).length > 0) continue;
    hits.push({ id: rule.id, label: rule.label, word, severity: rule.severity });
  }
  return hits;
}

/** 연락처 · 링크 · 긴 숫자 모양(출력에서 나오면 안 됨) */
export function contactHit(text: string): Hit | null {
  return hasContactShape(text) ? { id: 'contact', label: '연락처 · 링크 모양', word: '', severity: 'block' } : null;
}

/** 출력 글에서 새로 생긴 아라비아 숫자 덩어리(입력에 없던 것) */
export function newDigitRuns(output: string, input: string): string[] {
  const runs = output.match(/[0-9０-９]+/g) ?? [];
  const nIn = input.normalize('NFKC');
  return runs.filter((r) => !nIn.includes(r.normalize('NFKC')));
}
